    /// <summary>
    /// Event used to convey a patch status registry snapshot received from the FNE.
    /// </summary>
    public class PatchStatusReceivedEvent : EventArgs
    {
        /// <summary>
        /// Registry snapshot.
        /// </summary>
        public PatchStatusRegistrySnapshot Snapshot { get; }

        /// <summary>
        /// Initializes a new instance of the <see cref="PatchStatusReceivedEvent"/> class.
        /// </summary>
        /// <param name="snapshot">Registry snapshot.</param>
        public PatchStatusReceivedEvent(PatchStatusRegistrySnapshot snapshot)
        {
            Snapshot = snapshot;
        }
    } // public class PatchStatusReceivedEvent

    /// <summary>
    /// Represents a talkgroup member participating in a console patch.
    /// </summary>
    /// <remarks>This mirrors PatchStatusRegistry::PatchMember in dvmhost.</remarks>
    public class PatchStatusMember
    {
        /// <summary>
        /// System name for the member.
        /// </summary>
        public string System { get; set; } = string.Empty;
        /// <summary>
        /// Digital mode for the member.
        /// </summary>
        /// <remarks>The FNE normalizes this to lower case.</remarks>
        public string Mode { get; set; } = "unknown";
        /// <summary>
        /// Talkgroup ID for the member.
        /// </summary>
        public uint Tgid { get; set; }
        /// <summary>
        /// Timeslot for the member, if applicable.
        /// </summary>
        public byte Slot { get; set; }
        /// <summary>
        /// Stable talkgroup lookup key generated by the FNE.
        /// </summary>
        /// <remarks>Only populated on records received from the FNE.</remarks>
        public string Key { get; set; } = string.Empty;

        /*
        ** Methods
        */

        /// <summary>
        /// Builds the stable talkgroup lookup key the FNE generates for a member.
        /// </summary>
        /// <returns>Talkgroup key in the form "mode:tgid:slot".</returns>
        public string BuildKey()
        {
            return BuildKey(Mode, Tgid, Slot);
        }

        /// <summary>
        /// Builds the stable talkgroup lookup key the FNE generates for a member.
        /// </summary>
        /// <param name="mode">Digital mode.</param>
        /// <param name="tgid">Talkgroup ID.</param>
        /// <param name="slot">Timeslot.</param>
        /// <returns>Talkgroup key in the form "mode:tgid:slot".</returns>
        public static string BuildKey(string mode, uint tgid, byte slot)
        {
            return string.Format(CultureInfo.InvariantCulture, "{0}:{1}:{2}",
                (mode ?? string.Empty).ToLowerInvariant(), tgid, (uint)slot);
        }
    } // public class PatchStatusMember

    /// <summary>
    /// Represents one console patch.
    /// </summary>
    /// <remarks>This mirrors PatchStatusRegistry::PatchRecord in dvmhost.</remarks>
    public class PatchStatusPatch
    {
        /// <summary>
        /// Console-defined patch ID.
        /// </summary>
        public string PatchId { get; set; } = string.Empty;
        /// <summary>
        /// Flag indicating whether the patch is active.
        /// </summary>
        public bool Active { get; set; } = true;
        /// <summary>
        /// Flag indicating whether the patch is one-way.
        /// </summary>
        public bool OneWay { get; set; }
        /// <summary>
        /// Talkgroup members in the patch.
        /// </summary>
        public List<PatchStatusMember> Members { get; set; } = new List<PatchStatusMember>();

        /// <summary>
        /// Console peer ID that owns the patch.
        /// </summary>
        /// <remarks>Only populated in the flattened "patches" array of a registry snapshot.</remarks>
        public uint PeerId { get; set; }
        /// <summary>
        /// FNE peer ID where the patch originated.
        /// </summary>
        /// <remarks>Only populated in the flattened "patches" array of a registry snapshot.</remarks>
        public uint OriginFnePeerId { get; set; }
        /// <summary>
        /// Console peer display name that owns the patch.
        /// </summary>
        /// <remarks>Only populated in the flattened "patches" array of a registry snapshot.</remarks>
        public string PeerName { get; set; } = string.Empty;
    } // public class PatchStatusPatch

    /// <summary>
    /// Represents a console peer's complete patch status snapshot.
    /// </summary>
    /// <remarks>This mirrors PatchStatusRegistry::PeerPatchSnapshot in dvmhost.</remarks>
    public class PatchStatusPeer
    {
